#!/usr/bin/env python3
"""Train/evaluate a small Decision Tree and export standalone C++ inference."""

import argparse
import csv
import json
from collections import Counter
from pathlib import Path

from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score
from sklearn.tree import DecisionTreeClassifier

FEATURES = [
    "upper_available", "upper_pdr_estimate", "upper_latency_ms", "upper_hops",
    "lower_available", "lower_pdr_estimate", "lower_latency_ms", "lower_hops",
]
LABEL = "label_route"
MODEL_VERSION = "decision-tree-v1-seed-20261101"


def load_rows(path: Path):
    with path.open(newline="") as stream:
        return list(csv.DictReader(stream))


def cpp_header(model: DecisionTreeClassifier) -> str:
    tree = model.tree_
    classes = [int(v) for v in model.classes_]
    leaf_labels = []
    for node in range(tree.node_count):
        counts = tree.value[node][0]
        leaf_labels.append(classes[max(range(len(classes)), key=lambda i: counts[i])])
    feature = list(map(int, tree.feature))
    left = list(map(int, tree.children_left))
    right = list(map(int, tree.children_right))
    threshold = [float(v) for v in tree.threshold]

    def arr(name, ctype, values):
        rendered = ", ".join((f"{v:.12g}" if isinstance(v, float) else str(v)) for v in values)
        return f"inline constexpr {ctype} {name}[{len(values)}] = {{{rendered}}};\n"

    header = '''// Generated by ml/train_tree.py. Synthetic route scenario model; not hardware-trained.
#pragma once
#include <array>
#include <cmath>
namespace p12ganesh::ml {
inline constexpr const char *MODEL_VERSION = "decision-tree-v1-seed-20261101";
struct RouteFeatures {
    double upper_available, upper_pdr_estimate, upper_latency_ms, upper_hops;
    double lower_available, lower_pdr_estimate, lower_latency_ms, lower_hops;
};
inline std::array<double, 8> values(const RouteFeatures& f) {
    return {f.upper_available, f.upper_pdr_estimate, f.upper_latency_ms, f.upper_hops,
            f.lower_available, f.lower_pdr_estimate, f.lower_latency_ms, f.lower_hops};
}
'''
    header += arr("feature", "int", feature)
    header += arr("left", "int", left)
    header += arr("right", "int", right)
    header += arr("threshold", "double", threshold)
    header += arr("leaf_label", "int", leaf_labels)
    header += '''inline int predict(const RouteFeatures& input) {
    const auto x = values(input);
    for (double value : x) if (!std::isfinite(value)) return -2;
    int node = 0;
    while (left[node] != -1) node = (x[feature[node]] <= threshold[node]) ? left[node] : right[node];
    return leaf_label[node];
}
inline double expectedCost(double pdr, double latencyMs) {
    return pdr * latencyMs + (1.0 - pdr) * 1000.0;
}
inline bool usable(bool available, double pdr, double latencyMs, double hops) {
    return available && std::isfinite(pdr) && pdr >= 0 && pdr <= 1 &&
           std::isfinite(latencyMs) && latencyMs >= 0 && std::isfinite(hops) && hops >= 1;
}
inline int selectSafely(int prediction, const RouteFeatures& f) {
    const bool upper = usable(f.upper_available >= 0.5, f.upper_pdr_estimate, f.upper_latency_ms, f.upper_hops);
    const bool lower = usable(f.lower_available >= 0.5, f.lower_pdr_estimate, f.lower_latency_ms, f.lower_hops);
    if (prediction == 0 && upper) return 0;
    if (prediction == 1 && lower) return 1;
    if (!upper && !lower) return -1;
    if (!upper) return 1;
    if (!lower) return 0;
    const double upperCost = expectedCost(f.upper_pdr_estimate, f.upper_latency_ms);
    const double lowerCost = expectedCost(f.lower_pdr_estimate, f.lower_latency_ms);
    if (upperCost != lowerCost) return upperCost < lowerCost ? 0 : 1;
    return f.upper_hops <= f.lower_hops ? 0 : 1;
}
} // namespace p12ganesh::ml
'''
    return header


def train(data_path: Path, model_path: Path, metrics_path: Path, header_path: Path):
    rows = load_rows(data_path)
    training = [r for r in rows if r["split"] == "train"]
    testing = [r for r in rows if r["split"] == "test"]
    if not training or not testing:
        raise ValueError("dataset must contain non-empty train and test partitions")
    x_train = [[float(r[name]) for name in FEATURES] for r in training]
    y_train = [int(r[LABEL]) for r in training]
    x_test = [[float(r[name]) for name in FEATURES] for r in testing]
    y_test = [int(r[LABEL]) for r in testing]

    model = DecisionTreeClassifier(max_depth=4, min_samples_leaf=3, random_state=20261101)
    model.fit(x_train, y_train)
    predictions = model.predict(x_test).astype(int).tolist()
    labels = sorted(set(y_train) | set(y_test))
    metrics = {
        "model_version": MODEL_VERSION,
        "model": "sklearn.tree.DecisionTreeClassifier",
        "sklearn_version": __import__("sklearn").__version__,
        "features": FEATURES,
        "target": LABEL,
        "objective": "minimize expected completion cost = pdr*delay_ms + (1-pdr)*1000ms; unavailable routes excluded; ties prefer fewer hops then upper path",
        "data_origin": "synthetic controlled route scenarios; not OMNeT packet measurements or hardware measurements",
        "seed": 20261101,
        "split": "scenario run ids 0-79 train, 80-99 held out; no run id appears in both partitions",
        "training_rows": len(training),
        "test_rows": len(testing),
        "train_label_counts": dict(Counter(y_train)),
        "test_label_counts": dict(Counter(y_test)),
        "accuracy": accuracy_score(y_test, predictions),
        "macro_f1": f1_score(y_test, predictions, labels=labels, average="macro", zero_division=0),
        "confusion_matrix_labels": labels,
        "confusion_matrix": confusion_matrix(y_test, predictions, labels=labels).tolist(),
        "classification_report": classification_report(y_test, predictions, labels=labels, output_dict=True, zero_division=0),
        "max_depth": int(model.get_depth()),
        "leaf_count": int(model.get_n_leaves()),
    }
    model_obj = {
        "metadata": metrics,
        "classes": [int(v) for v in model.classes_],
        "tree": {
            "feature": list(map(int, model.tree_.feature)),
            "threshold": [float(v) for v in model.tree_.threshold],
            "children_left": list(map(int, model.tree_.children_left)),
            "children_right": list(map(int, model.tree_.children_right)),
            "leaf_label": [
                int(model.classes_[max(range(len(model.classes_)), key=lambda i: model.tree_.value[n][0][i])])
                for n in range(model.tree_.node_count)
            ],
        },
    }
    for path in (model_path, metrics_path, header_path):
        path.parent.mkdir(parents=True, exist_ok=True)
    model_path.write_text(json.dumps(model_obj, indent=2) + "\n")
    metrics_path.write_text(json.dumps(metrics, indent=2) + "\n")
    header_path.write_text(cpp_header(model))
    return metrics, model


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, default=Path("ml/data/route_scenarios.csv"))
    parser.add_argument("--model", type=Path, default=Path("ml/artifacts/route_tree.json"))
    parser.add_argument("--metrics", type=Path, default=Path("ml/artifacts/evaluation.json"))
    parser.add_argument("--header", type=Path, default=Path("ml/generated/DecisionTreeModel.h"))
    args = parser.parse_args()
    metrics, _ = train(args.data, args.model, args.metrics, args.header)
    print(f"test accuracy={metrics['accuracy']:.4f} macro_f1={metrics['macro_f1']:.4f} rows={metrics['test_rows']}")
    print(f"wrote {args.model}, {args.metrics}, and {args.header}")


if __name__ == "__main__":
    main()
